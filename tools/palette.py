def rgb(color):
    value = color.lstrip("#")[:6]
    return tuple(int(value[i:i + 2], 16) for i in (0, 2, 4))


def hex_color(channels):
    return "#" + "".join(f"{max(0, min(255, round(c))):02X}" for c in channels)


def mix(base, other, ratio):
    first, second = rgb(base), rgb(other)
    return hex_color(tuple(first[i] + (second[i] - first[i]) * ratio for i in range(3)))


def alpha(color, ratio):
    return f"{color[:7].upper()}{max(0, min(255, round(255 * ratio))):02X}"


def bare(color):
    return color.lstrip("#")[:6].lower()


